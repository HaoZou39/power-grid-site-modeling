import assert from 'node:assert/strict';
import { HISTORY_EVALUATION, autoPendingPoses, batches, evaluationKey, pendingPoses, poseFreshness, stalePoses, zoneStalePoses } from '../../.tmp-problem-snapshot/map/pose_evaluation.js';
import { STALE, choiceStatus, compareChart, manualChoice, measuredChoice, presentChoice, restoreChoice, schemeCard, unmeasured } from '../../.tmp-problem-snapshot/map/decision_run.js';
import { exportSolutionsJson } from '../../.tmp-problem-snapshot/map/solution_export.js';
import { SiteEdit } from '../../.tmp-problem-snapshot/map/site_edit.js';
import { visibleAtLevel } from '../../.tmp-problem-snapshot/map/solution_diversity.js';
import { paretoLayerCounts, selectExportPoses } from '../../.tmp-problem-snapshot/map/scene_export.js';
import { toolbarCommands } from '../../.tmp-problem-snapshot/map/toolbar_commands.js';
import { toSnapshot } from '../../.tmp-problem-snapshot/agent/workspace_snapshot.js';

const edit = new SiteEdit();
const pose = manualChoice('manual-1', { x: 900, y: 900 }, 0);
const config = edit.searchConfig();
const key = evaluationKey('scene', config, pose);
assert.equal(evaluationKey('scene', { ...config, include_demand: true, scene_name: 'ignored' }, pose), key);
for (const change of [{ road_setback_m: 17 }, { road_product_id: 'new' }, { farmland_content_sha256: 'new' }, { origin_x: 10 }, { field_policy: 'blocked' }]) {
  assert.notEqual(evaluationKey('scene', { ...config, ...change }, pose), key);
}
const landInputs = { ...config, road_product_id: 'same', farmland_content_sha256: 'same', landuse_revision: 1 };
const beforeLandEdit = { ...pose, evaluatedFor: evaluationKey('scene', landInputs, pose) };
const afterLandEdit = { ...landInputs, landuse_revision: 2 };
const landKeyOf = (p) => evaluationKey('scene', afterLandEdit, p);
assert.notEqual(landKeyOf(beforeLandEdit), beforeLandEdit.evaluatedFor);
assert.deepEqual(pendingPoses([beforeLandEdit], landKeyOf, new Set(), new Map()), [beforeLandEdit]);
// Requests and failures from the old revision must not suppress the new evaluation.
assert.deepEqual(pendingPoses([beforeLandEdit], landKeyOf,
  new Set([beforeLandEdit.evaluatedFor]), new Map([[beforeLandEdit.evaluatedFor, 'old failure']])), [beforeLandEdit]);
const moved = { ...pose, x: 901 };
assert.notEqual(evaluationKey('scene', config, moved), key);
assert.deepEqual(batches(Array.from({ length: 201 }, (_, i) => i)).map((batch) => batch.length), [200, 1]);
const keyOf = (p) => evaluationKey('scene', config, p);
assert.deepEqual(pendingPoses([pose], keyOf, new Set([key]), new Map()), []);
assert.deepEqual(pendingPoses([pose], keyOf, new Set(), new Map([[key, 'failed']])), []);
assert.deepEqual(pendingPoses([{ ...moved, evaluatedFor: key }], keyOf, new Set(), new Map()), [{ ...moved, evaluatedFor: key }]);
const row = { dem_soft: 1, road_distance: 2, demand_distance: 3, road_haul_m: '', offroad_haul_m: 4, haul_rise_m: 5, obstacle_hard_count: 0, is_feasible: true };
const measured = measuredChoice(pose, row, key);
assert.equal(measured.baseline.demSoft, measured.demSoft);
assert.equal(measured.evaluatedFor, key);
assert.equal(unmeasured(measured).evaluatedFor, undefined);
const pendingSnapshot = toSnapshot(edit.withPoses([unmeasured(measured)])).poses[0];
assert.equal(pendingSnapshot.objectives, undefined);
assert.equal(pendingSnapshot.feasible, undefined);
assert.equal(toSnapshot(edit.withPoses([measuredChoice(pose, { ...row, is_feasible: false }, landKeyOf(pose))])).poses[0].feasible, false);
assert.equal(pendingPoses([unmeasured(measured)], keyOf, new Set(), new Map()).length, 1);
assert.equal(restoreChoice(measured).evaluatedFor, undefined);
const again = measuredChoice({ ...measured, x: 910 }, { ...row, dem_soft: 9 }, 'second');
assert.equal(again.baseline.demSoft, measured.demSoft);
const choices = edit.addPose(pose).addPose({ ...pose, id: 'b' }).addPose({ ...pose, id: 'c' }).selectPose('b');
assert.equal(choices.removePose('b').selectedPoseId, 'c');
assert.equal(choices.removePose('c').selectedPoseId, 'b');
assert.equal(choices.selectPose('c').removePose('c').selectedPoseId, 'b');
assert.equal(edit.addPose(pose).removePose(pose.id).selectedPoseId, null);
assert.equal(visibleAtLevel(pose, 1), true);
assert.deepEqual(paretoLayerCounts([pose]), { 1: 0, 2: 0, 3: 0 });
assert.deepEqual(selectExportPoses([pose], { 1: false, 2: false, 3: false }), [pose]);
const commands = toolbarCommands({ tool: 'pan', setTool() {}, focusSite() {}, notify() {}, poseAddDisabled: true });
assert.equal(commands.find((item) => item.id === 'pose-add').disabled, true);
const ring = [{ x: 100, y: 100 }, { x: 140, y: 100 }, { x: 140, y: 140 }];
const zoned = edit.addExclusion(ring);
const zoneConfig = zoned.searchConfig();
const stored = measured;
const freshness = (pose, inputs) => poseFreshness(pose.evaluatedFor, 'scene', inputs, pose);
assert.equal(freshness(stored, config), 'current');
assert.equal(freshness(stored, zoneConfig), 'zone-stale');
assert.equal(freshness(stored, edit.addFeasible(ring).searchConfig()), 'zone-stale');
assert.equal(freshness(stored, zoned.removeRegion(zoned.regions[0].id).searchConfig()), 'current');
assert.equal(autoPendingPoses([stored], (pose) => evaluationKey('scene', zoneConfig, pose), new Set(), new Map(), (pose) => freshness(pose, zoneConfig)).length, 0);
assert.equal(zoneStalePoses([stored], (pose) => freshness(pose, zoneConfig)).length, 1);
assert.equal(zoneStalePoses(zoned.poses, (pose) => freshness(pose, zoneConfig)).length, 0);
assert.equal(autoPendingPoses([], () => '', new Set(), new Map(), () => 'zone-stale').length, 0);
const hidden = { ...stored, id: 'hidden', paretoLayer: 3 };
assert.equal(freshness(hidden, zoneConfig), 'zone-stale');
assert.equal(zoneStalePoses([stored, hidden], (pose) => freshness(pose, zoneConfig)).length, 2);
const movedPose = { ...stored, x: stored.x + 5 };
assert.equal(freshness(movedPose, config), 'pending');
assert.equal(autoPendingPoses([movedPose], (pose) => evaluationKey('scene', config, pose), new Set(), new Map(), (pose) => freshness(pose, config)).length, 1);
const shown = presentChoice(stored, 'zone-stale');
assert.equal(shown.demSoft, STALE);
assert.equal(shown.feasible, STALE);
assert.equal(shown.obstacleHardCount, STALE);
assert.equal(shown.x, stored.x);
assert.equal(shown.evaluatedFor, stored.evaluatedFor);
assert.notEqual(stored.demSoft, STALE);
assert.equal(unmeasured(stored).demSoft, '重算中');
const report = { offroadHaulM: 99, haulRiseM: 88, accessSlopeDeg: 4, accessWarning: false, roadHaulM: 7 };
const status = choiceStatus(shown, report);
assert.equal(status.find((row) => row.label === '地形平整度').value, STALE);
assert.equal(status.find((row) => row.label === '进站长度（m）').value, STALE);
assert.equal(status.find((row) => row.label === '可行性').value, STALE);
assert.notEqual(status.find((row) => row.label === '进站坡度（°）').value, STALE);
const editedShown = presentChoice({ ...stored, x: stored.x + 8 }, 'zone-stale');
assert.match(choiceStatus(editedShown, null).find((row) => row.label === '地形平整度').value, /原始结果／旧约束/);
const chart = compareChart([
  { id: 'a', name: 'a', choice: shown },
  { id: 'b', name: 'b', choice: shown },
]);
assert.equal(chart.labels.length, 0);
const card = schemeCard(shown, report, true, true);
assert.equal(card.decisions.find((row) => row.label === '可行性').value, STALE);
assert.equal(card.objectives.find((row) => row.label === '地形平整度').value, STALE);
assert.equal(card.objectives.find((row) => row.label === '沿路长度（m）').value, STALE);
assert.notEqual(card.objectives.find((row) => row.label === '进站坡度（°）').value, STALE);
const updated = measuredChoice(stored, row, evaluationKey('scene', zoneConfig, stored));
assert.equal(freshness(updated, zoneConfig), 'current');
assert.equal(presentChoice(updated, 'current'), updated);
assert.notEqual(updated.demSoft, STALE);
const exported = JSON.parse(exportSolutionsJson('scene', 77, 51, [shown]));
assert.equal(exported.solutions[0].dem_soft, null);
assert.equal(exported.solutions[0].obstacle_hard_count, null);
assert.equal(exported.solutions[0].is_feasible, null);
assert.equal(exported.solutions[0].x_m, stored.x);
assert.equal(toSnapshot(edit.withPoses([shown])).poses[0].objectives, undefined);
assert.equal(toSnapshot(edit.withPoses([shown])).poses[0].feasible, undefined);
assert.ok(toSnapshot(edit.withPoses([stored])).poses[0].objectives);
const inFlight = new Set();
const firstPass = zoneStalePoses([stored, hidden], (pose) => freshness(pose, zoneConfig))
  .filter((pose) => !inFlight.has(evaluationKey('scene', zoneConfig, pose)));
assert.equal(firstPass.length, 2);
firstPass.forEach((pose) => inFlight.add(evaluationKey('scene', zoneConfig, pose)));
assert.equal(zoneStalePoses([stored, hidden], (pose) => freshness(pose, zoneConfig))
  .filter((pose) => !inFlight.has(evaluationKey('scene', zoneConfig, pose))).length, 0);
const changedAgain = zoned.addFeasible([{ x: 200, y: 200 }, { x: 240, y: 200 }, { x: 240, y: 240 }]);
assert.notEqual(evaluationKey('scene', changedAgain.searchConfig(), stored), evaluationKey('scene', zoneConfig, stored));
assert.equal(freshness(updated, changedAgain.searchConfig()), 'zone-stale');
const imported = { ...stored, evaluatedFor: HISTORY_EVALUATION };
assert.equal(freshness(imported, config), 'history-stale');
assert.equal(autoPendingPoses([imported], (pose) => evaluationKey('scene', config, pose), new Set(), new Map(), (pose) => freshness(pose, config)).length, 0);
assert.equal(stalePoses([imported, stored], (pose) => freshness(pose, zoneConfig)).map((pose) => pose.evaluatedFor).sort().join(','), [HISTORY_EVALUATION, stored.evaluatedFor].sort().join(','));
assert.equal(presentChoice(imported, 'history-stale').demSoft, STALE);
assert.notEqual(imported.demSoft, STALE);
const movedImport = { ...imported, x: imported.x + 4 };
assert.equal(freshness(movedImport, config), 'pending');
assert.equal(autoPendingPoses([movedImport], (pose) => evaluationKey('scene', config, pose), new Set(), new Map(), (pose) => freshness(pose, config)).length, 1);
console.log('pose evaluation and manual schemes: passed');
