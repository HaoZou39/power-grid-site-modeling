import assert from "node:assert/strict";
import { File } from "node:buffer";
import { cadFileBody, dataImportBody, MAX_CAD_FILE_BYTES } from "../../.tmp-problem-snapshot/map/scene_data_import.js";
const farm = new File(["farm"], "farm.zip");
const roads = new File(["roads"], "roads.rar");
assert.throws(() => dataImportBody(null, null, ""), /至少/);
assert.throws(() => dataImportBody(null, roads, " "), /来源/);
assert.deepEqual([...dataImportBody(farm, null, "").keys()], ["farmland"]);
const combined = dataImportBody(farm, roads, " 高德 ");
assert.deepEqual([...combined.keys()], ["farmland", "roads", "provider"]);
assert.equal(combined.get("provider"), "高德");
assert.equal(combined.get("roads").name, "roads.rar");
assert.deepEqual([...dataImportBody(null, roads, "gaode").keys()], ["roads", "provider"]);
const cad = new File(["drawing"], "苍南莒溪镇.DWG");
const cadBody = cadFileBody(cad);
assert.deepEqual([...cadBody.keys()], ["file"]);
assert.equal(cadBody.get("file").name, cad.name);
assert.equal(await cadBody.get("file").text(), "drawing");
assert.equal(cadFileBody(new File(["drawing"], "drawing.dxf")).get("file").name, "drawing.dxf");
assert.throws(() => cadFileBody(new File(["drawing"], "drawing.zip")), /DWG.*DXF/);
assert.throws(() => cadFileBody(new File([], "empty.dwg")), /不能为空/);
const oversized = new File(["drawing"], "large.dwg");
Object.defineProperty(oversized, "size", { value: MAX_CAD_FILE_BYTES + 1 });
assert.throws(() => cadFileBody(oversized), /80 MiB/);
console.log("scene data import request combinations: passed");
