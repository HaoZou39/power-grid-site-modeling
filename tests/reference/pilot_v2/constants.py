def _build_cost_arrays():
    """Compile dict-based cost tables into flat numpy arrays for O(1) lookup."""
    if MAP_MODE == "routing_coarse":
        sit   = np.full(512, 8.0,  dtype=np.float64)
        cross = np.zeros(512,       dtype=np.float64)
        line  = np.full(512, 5.5,  dtype=np.float64)
        for _k, _v in ROUTE_TERRAIN_SITING_COST.items():
            if 0 <= _k < 512:
                sit[_k] = _v
        for _k, _v in ROUTE_LINE_CROSSING_COST.items():
            if 0 <= _k < 512:
                cross[_k] = _v
        for _k, _v in ROUTE_LINE_TERRAIN_COST.items():
            if 0 <= _k < 512:
                line[_k] = _v
    else:
        sit   = np.full(512, 2.0,  dtype=np.float64)
        cross = np.zeros(512,       dtype=np.float64)
        line  = np.full(512, 2.5,  dtype=np.float64)
        for _k, _v in TERRAIN_SITING_COST.items():
            if 0 <= _k < 512:
                sit[_k] = _v
        for _k, _v in LINE_CROSSING_COST.items():
            if 0 <= _k < 512:
                cross[_k] = _v
                line[_k]  = max(line[_k], float(_v))
        for _k, _v in TERRAIN_SITING_COST.items():
            if 0 <= _k < 512:
                line[_k] = max(line[_k], 0.8 * float(_v))
    return sit, cross, line


