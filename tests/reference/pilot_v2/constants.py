def resolve_pop_size(default: int = DEFAULT_POP_SIZE) -> int:
    """Population size for a run, honouring the ``PILOT_POP_SIZE`` override.

    The override exists for budget-stress protocols that must reach every arm
    (all methods share this backbone) without editing the paper default. It is
    read at call time so that a value exported after import — including in
    ``ProcessPoolExecutor`` children — still takes effect.
    """
    raw = os.environ.get(POP_SIZE_ENV_VAR)
    if raw is None or not raw.strip():
        return int(default)
    value = int(raw)
    if value < 2:
        raise ValueError(f"{POP_SIZE_ENV_VAR} must be >= 2, got {value}")
    return value
