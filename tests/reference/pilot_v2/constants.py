def _maximize_objective_indices(n_obj: int) -> Tuple[int, ...]:
    """Return indices of objectives that should be maximised in raw space."""
    return tuple(idx for idx in PREFERENCE_MAXIMIZE_IDXS if idx < int(n_obj))


def _flip_higher_is_better_columns(arr: np.ndarray) -> np.ndarray:
    """Invert columns where higher raw value means better (safety, smoothness)."""
    out = np.asarray(arr, dtype=float).copy()
    if out.ndim == 1:
        out = out[None, :]
    for idx in _maximize_objective_indices(out.shape[1]):
        out[:, idx] = 1.0 - out[:, idx]
    return out
