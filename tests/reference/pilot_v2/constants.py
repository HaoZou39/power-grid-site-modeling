def _resolve_routing_map_path(project_dir: str = PROJECT_DIR) -> str:
    """Pick the best available routing map with a safe fallback order.

    Priority:
    1. Canonical existing-line / hand-drawn map generated by the current toolchain.
    2. Legacy migration fallback from route_plan_v2. The current toolchain does
       not generate this filename anymore.
    3. Ordinary downsampled routing map.
    """
    candidates = (
        os.path.join(project_dir, "outputs", "routing_coarse_with_existing_class.npy"),
        os.path.join(
            project_dir,
            "outputs",
            "existing_line_mask_template_exact_4_routing_coarse_with_existing_class.npy",
        ),
        os.path.join(
            project_dir,
            "outputs",
            "satellite_27.548982_120.377612_r2.00km_z19_full_preview_routing_coarse_mask_downsampled.npy",
        ),
    )
    for path in candidates:
        if os.path.isfile(path):
            return path
    return candidates[-1]

