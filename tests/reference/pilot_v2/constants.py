def resolve_init_strategy() -> str:
    """Generation-0 seeding strategy, honouring ``PILOT_INIT_STRATEGY``.

    The paper default combines multi-resolution A* anchors with RRT diversity.
    The weaker modes exist for the initialization-strength ablation, which asks
    what the evolutionary loop contributes once the heuristic anchors are taken
    away. Only generation-0 seeding is affected; per-generation restarts keep
    their own mechanism.
    """
    raw = (os.environ.get(INIT_STRATEGY_ENV_VAR) or "astar_rrt").strip().lower()
    if raw not in INIT_STRATEGIES:
        raise ValueError(
            f"{INIT_STRATEGY_ENV_VAR} must be one of {INIT_STRATEGIES}, got {raw!r}"
        )
    return raw


